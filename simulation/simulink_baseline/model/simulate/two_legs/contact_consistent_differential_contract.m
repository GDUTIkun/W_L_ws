function contract = contact_consistent_differential_contract()
%CONTACT_CONSISTENT_DIFFERENTIAL_CONTRACT Frozen Phase-5 G1 design contract.
% This file records inspection-backed contact observability and metadata rules.
% Candidate-model fields are appended by the G1 model-contract task.

contract = struct();
contract.contractVersion = "05-01-G1";
contract.convention = "(right-left)/2";
contract.contactObservability = contactObservability();
contract.metadataRules = metadataRules();
contract.stateCore = ["xiDelta", "dxiDelta", "vRollDelta"];
contract.inputContract = realizableInputContract();
contract.candidateInterface = candidateInterface( ...
    contract.stateCore, contract.contactObservability);
contract.modelLadder = modelLadder();
contract.rejectedSubstitutions = [ ...
    "abstractSlowContactState", "independentForceAndTorqueInputs", ...
    "higherOrderArx", "broadHistoryTerms", "neuralSubstitute"];
contract.validationGates = validationGates();
contract.executionBoundary = executionBoundary();
contract.approvalRule = ...
    "No NMPC integration readiness claim until multi-step, free-run, held-seed, and held-yaw gates pass without relaxed limits.";
contract.escalationConditions = [ ...
    "Frozen convention or three-state core must change", ...
    "Audited input basis or WBC architecture must change", ...
    "Plant parameters, controller limits, or validation thresholds must change", ...
    "Implementation requires more than smoke execution"];
contract.scopeFences = [ ...
    "No NMPC prediction-dynamics replacement in this phase", ...
    "No WBC objective, constraint, friction, torque, or bound redesign", ...
    "No plant-parameter change", ...
    "No large-yaw acceptance, terrain/contact switching, or hardware claim"];
end

function input = realizableInputContract()
persistent cachedAudit
if isempty(cachedAudit)
    cachedAudit = audit_differential_realizable_input_basis();
end
audit = cachedAudit;
input = struct();
input.name = audit.name;
input.rank = audit.rank;
input.basis = audit.basis;
input.targetPairBasis = audit.targetPairBasis;
input.taskProjection = audit.taskProjection;
input.nullspaceDimension = audit.nullspaceDimension;
input.nullspaceBasis = audit.nullspaceBasis;
input.coupledWrenchImage = audit.coupledWrenchImage;
input.limits = audit.limits;
input.frames = audit.frames;
input.unit = audit.inputUnit;
input.convention = audit.convention;
input.realizedInputRequired = true;
input.commandToRealizedDiagnosticsRequired = true;
input.auditArtifactPath = audit.artifactPath;
end

function interface = candidateInterface(stateCore, observability)
directNames = string({observability.availableDirect.name});
interface = struct();
interface.signature = ...
    "xDotDiff=f(xDiffCore,uDiffRealizable,contactState,configuration)";
interface.stateArgument = "xDiffCore";
interface.stateOrder = stateCore;
interface.inputArgument = "uDiffRealizable";
interface.inputDimension = 1;
interface.contactArgument = "contactState";
interface.contactStateOrder = directNames;
interface.contactStatePolicy = ...
    "Use only inspection-confirmed direct physical outputs; current order is empty and proxies are forbidden.";
interface.configurationArgument = "configuration";
interface.configurationFields = ["forwardSpeed", "yawRate"];
interface.output = "xDotDiff";
interface.outputOrder = stateCore;
interface.onlineEvaluable = true;
interface.interpretable = true;
interface.stateJacobian = "df/dxDiffCore [3x3]";
interface.inputJacobian = "df/duDiffRealizable [3x1]";
interface.contactJacobian = "df/dcontactState [3xnContact]";
interface.configurationJacobian = "df/dconfiguration [3xnConfiguration]";
interface.linearizationA = "stateJacobian";
interface.linearizationB = "inputJacobian";
interface.linearizationContact = "contactJacobian";
interface.linearizationConfiguration = "configurationJacobian";
interface.evaluationOutputs = [ ...
    "xDotDiff", "stateJacobian", "inputJacobian", ...
    "contactJacobian", "configurationJacobian"];
end

function ladder = modelLadder()
ladder = [
    modelStep(1, "physicalOrAlgebraicContactModel", ...
        "preferred", "Use the frozen state, realized input, and direct contact state."), ...
    modelStep(2, "lowOrderNonlinearModel", ...
        "allowed-after-evidence", ...
        "Use only if the physical/algebraic form cannot pass the frozen gates."), ...
    modelStep(3, "stateDependentParameterization", ...
        "conditional", ...
        "Use only when residual and held-out evidence identifies the dependency.")];
end

function step = modelStep(priority, modelClass, disposition, condition)
step = struct("priority", priority, "modelClass", modelClass, ...
    "disposition", disposition, "condition", condition);
end

function gates = validationGates()
gates = [
    gate("signedExcitation", ...
        "Positive and negative realizable input; coupled realized wrench and command-to-realized diagnostics."), ...
    gate("preBoundaryAndFullWindow", ...
        "Report both pre-boundary and complete-window metrics with unchanged cutoffs."), ...
    gate("heldSeed", ...
        "Leave-one-seed validation using the retained Model-C infrastructure."), ...
    gate("heldYaw", ...
        "Leave-one-yaw validation using the retained Model-C infrastructure."), ...
    gate("multiStep", ...
        "One-second and configured multi-step prediction metrics."), ...
    gate("freeRun", ...
        "Complete free-run R-squared, RMSE, bias, and boundedness evidence."), ...
    gate("residualCorrelation", ...
        "Residual correlation against state, realized input, direct contact, and configuration fields."), ...
    gate("residualPsd", ...
        "Residual PSD including an explicit check near 1.9 Hz before any order increase."), ...
    gate("mirror", ...
        "Positive/negative and left/right mirror behavior under (right-left)/2."), ...
    gate("torquePath", ...
        "Retained torque-path diagnostics with unchanged torque limits.")];
end

function item = gate(name, evidence)
item = struct("name", name, "required", true, ...
    "thresholdPolicy", "reuse-existing-unrelaxed", "evidence", evidence);
end

