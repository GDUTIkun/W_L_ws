function observability = contactObservability()
contactName = "Spatial" + newline + "Contact Force";
contactName1 = "Spatial" + newline + "Contact Force1";
observability = struct();
observability.inspectionMethod = ...
    "MATLAB load_system/find_system/get_param inspection of current SLX files";
observability.inspectedModels = [
    struct("model", "source.slx", ...
        "subsystem", "source/PD_only", ...
        "contactBlocks", ["source/PD_only/" + contactName, ...
            "source/PD_only/" + contactName1], ...
        "contactBlockCount", 2, ...
        "transformSensorCount", 0), ...
    struct("model", "source_common.slx", ...
        "subsystem", "source_common/PD_only", ...
        "contactBlocks", "source_common/PD_only/" + contactName1, ...
        "contactBlockCount", 1, ...
        "transformSensorCount", 0)];
observability.inspectionEvidence = struct( ...
    "contactBlockType", "Simscape Multibody Spatial Contact Force", ...
    "normalModel", "SmoothSpringDamper", ...
    "frictionModel", "SmoothStickSlip", ...
    "simulinkSignalInputCount", 0, ...
    "simulinkSignalOutputCount", 0, ...
    "conservingPortCount", 2, ...
    "normalForceSensing", "off", ...
    "frictionForceSensing", "off", ...
    "transformSensorCount", 0);

observability.availableDirect = emptyDirectSignal();
inspectedContactLocations = [
    "source/PD_only/" + contactName, ...
    "source/PD_only/" + contactName1, ...
    "source_common/PD_only/" + contactName1];
noSignalLimitation = "Contact physics exists, but the inspected blocks have " + ...
    "no enabled Simulink/physical-signal output for this quantity.";
observability.unavailableDirect = [
    unavailable("perWheelPenetration", "m", inspectedContactLocations, ...
        noSignalLimitation), ...
    unavailable("perWheelNormalCompression", "m", ...
        inspectedContactLocations, noSignalLimitation), ...
    unavailable("perWheelRollingSlip", "m/s", ...
        inspectedContactLocations, noSignalLimitation), ...
    unavailable("perWheelRelativeContactVelocity", "m/s", ...
        inspectedContactLocations, noSignalLimitation), ...
    unavailable("perWheelNormalForce", "N", ...
        inspectedContactLocations, ...
        "Normal-force sensing is explicitly off in every inspected contact block."), ...
    unavailable("perWheelFrictionForce", "N", ...
        inspectedContactLocations, ...
        "Friction-force sensing is explicitly off in every inspected contact block.")];

observability.excludedProxies = [
    proxy("normalLoadDifference", ...
        "spatial_two_leg_qp_core/debug.contactForceDifferential", ...
        "analytic WBC contact-force solution, not Simscape contact deformation"), ...
    proxy("filteredOrRealizedInput", ...
        "spatial_two_leg_qp_core/debug.wrenchFeasible", ...
        "controller-side realized wrench, not a physical contact state"), ...
    proxy("rollingConfigurationResidual", ...
        "spatial_two_leg_qp_core/debug.xiDifferential", ...
        "wheel configuration difference, not contact penetration or compression"), ...
    proxy("contactAccelerationResidual", ...
        "spatial_two_leg_qp_core/debug.contactResidual", ...
        "analytic WBC acceleration residual, not a measured Simscape contact output")];
end

function rules = metadataRules()
rules = struct();
rules.requiredForEveryAvailableDirectQuantity = [ ...
    "sourcePath", "unit", "sign", "sampleTime", "convention"];
rules.sourceRule = ...
    "Use the exact producing model/block and output port; do not infer a source.";
rules.unitRule = "Record the physical unit declared by the producing block.";
rules.signRule = ...
    "Record positive physical direction before forming a differential signal.";
rules.sampleTimeRule = ...
    "Record the actual producer/logging sample time; do not substitute NMPC rate.";
rules.leftRightRule = ...
    "Store left and right channels separately and derive differential as (right-left)/2.";
rules.proxyRule = ...
    "Controller force, input, configuration, and residual signals remain proxies and may not be relabeled as contact deformation.";
rules.unavailableRule = ...
    "Record inspected model locations and the precise missing or disabled output.";
end

