function signals = selectedSignals(leftBlock, rightBlock)
signals = repmat(emptySelected(), 0, 1);
for side = ["left", "right"]
    if side == "left"
        block = leftBlock;
        ownership = "Cylindrical Solid1 -> Revolute Joint5 -> configured left chain";
    else
        block = rightBlock;
        ownership = "Cylindrical Solid -> Revolute Joint2 -> configured right chain";
    end
    suffix = upper(extractBefore(side, 2)) + extractAfter(side, 1);
    signals(end + 1) = selected("contactStatus" + suffix, side, block, ...
        "con", "SenseContactSignal", ...
        "Scalar contact status for the geometry pair.", "1", ...
        "frame independent scalar", ...
        "1 means contact; 0 means separated", "scalar", ownership); %#ok<AGROW>
    signals(end + 1) = selected("contactPenetration" + suffix, side, block, ...
        "pen", "SensePenetrationDepth", ...
        "Geometric penetration depth between the two contact geometries.", "m", ...
        "frame independent scalar distance", ...
        "positive overlap; zero when not penetrating", "scalar", ownership); %#ok<AGROW>
    signals(end + 1) = selected("contactNormalForceMagnitude" + suffix, side, block, ...
        "fnm", "SenseNormalForceMagnitude", ...
        "Magnitude of the normal force between the contact geometries.", "N", ...
        "frame independent magnitude", ...
        "nonnegative magnitude; no direction sign", "scalar", ownership); %#ok<AGROW>
    signals(end + 1) = selected("contactFrictionForceMagnitude" + suffix, side, block, ...
        "ffrm", "SenseFrictionalForceMagnitude", ...
        "Magnitude of the frictional force between the contact geometries.", "N", ...
        "frame independent magnitude", ...
        "nonnegative magnitude; no direction sign", "scalar", ownership); %#ok<AGROW>
    signals(end + 1) = selected("contactNormalVelocity" + suffix, side, block, ...
        "vn", "SenseNormalVelocity", ...
        "Contact-point relative-velocity z component.", "m/s", ...
        "resolved in the block contact frame", ...
        "preserve the block-native +z component without inversion", "scalar", ownership); %#ok<AGROW>
    signals(end + 1) = selected("contactTangentialVelocity" + suffix, side, block, ...
        "vt", "SenseTangentialVelocity", ...
        "Contact-point relative tangential-velocity x/y components.", "m/s", ...
        "two components resolved in the block contact frame", ...
        "preserve block-native [+x;+y] components without inversion", "2-vector", ownership); %#ok<AGROW>
end
end

function item = emptySelected()
