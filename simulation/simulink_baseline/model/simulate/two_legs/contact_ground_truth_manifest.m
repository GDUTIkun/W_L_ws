    "sourcePort", "", "sensingParameter", "", "physicalMeaning", "", ...
    "unit", "", "frame", "", "sign", "", "sampleTime", "", ...
    "shape", "", "sideOwnership", "", "sourceClass", "", ...
    "observationOnly", false, "loggingName", "");
end

function item = selected(name, side, block, port, parameter, meaning, unit, ...
        frame, signRule, shape, ownership)
item = emptySelected();
item.name = name;
item.side = side;
item.sourceBlock = block;
item.sourcePort = port;
item.sensingParameter = parameter;
item.physicalMeaning = meaning;
item.unit = unit;
item.frame = frame;
item.sign = signRule;
item.sampleTime = ...
    "continuous Simscape physical signal; retain native timestamps";
item.shape = shape;
item.sideOwnership = ownership;
item.sourceClass = "plant_ground_truth";
item.observationOnly = true;
item.loggingName = name;
end

