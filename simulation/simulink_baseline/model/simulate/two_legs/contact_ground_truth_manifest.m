function manifest = contact_ground_truth_manifest()
%CONTACT_GROUND_TRUTH_MANIFEST Frozen Phase-6 contact observation contract.
% The manifest is a decision artifact.  It describes sensing outputs that
% may be exposed by G2, but it does not modify or save source.slx.

rightBlock = "source/PD_only/Spatial" + newline + "Contact Force";
leftBlock = "source/PD_only/Spatial" + newline + "Contact Force1";

manifest = struct();
manifest.schemaVersion = "contact-ground-truth/1.0.0";
manifest.status = "ready_for_g2";
manifest.canonicalConvention = canonicalConvention();
manifest.legacyMapping = legacyMapping(manifest.schemaVersion);
manifest.sourceClasses = sourceClasses();
manifest.selectedSignals = selectedSignals(leftBlock, rightBlock);
manifest.unavailableSignals = unavailableSignals(leftBlock, rightBlock);
manifest.proxySignals = proxySignals();
manifest.loggingContract = observationLoggingContract(manifest.selectedSignals);
manifest.scopeFences = scopeFences();
manifest.escalation = escalation();
manifest.inspection = inspectionEvidence(leftBlock, rightBlock);
end

function convention = canonicalConvention()
convention = struct( ...
    "schema", "phase-6-canonical-v1", ...
    "differential", "(right-left)/2", ...
    "commonMode", "(right+left)/2", ...
    "appliesTo", ["new contact quantities", "xiDeltaCanonical", ...
        "dxiDeltaCanonical", "vRollDelta", "uDiffRealizable"], ...
    "rawSidePolicy", "retain left and right channels before deriving pairs", ...
    "canonicalStateFields", ["xiDeltaCanonical", ...
        "dxiDeltaCanonical", "vRollDelta"], ...
    "legacyStateFields", ["xiDeltaLegacy", "dxiDeltaLegacy"], ...
    "pairDerivationPolicy", ...
        "derive canonical/common fields only after left/right timestamp alignment");
end

